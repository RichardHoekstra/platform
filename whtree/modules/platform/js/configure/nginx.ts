async function generateMimeTypes(types: Configuration["types"]): Promise<string> {
  const entries = types.filter(type => type.extension)
    .map(type => `    ${JSON.stringify(type.mimetype)} ${JSON.stringify(type.extension)};`);
  return `types {\n${entries.join("\n")}\n  }`;
}

async function generateBaseConfig(webserverConfig: Configuration, params: { pidFile: string; configRoot: string; routerFile: string }) {
  const serverSections: string[] = [];
  const trustedIp = process.env["WEBHARE_SECUREPORT_BINDIP"] || "127.0.0.1";
  const upstreamAddress = `${trustedIp.includes(":") ? `[${trustedIp}]` : trustedIp}:${getBasePort() + whconstant_webserver_hstrustedportoffset}`;

  for (const port of webserverConfig.ports) {
    if (!port.virtualhost || port.id === whwebserverconfig_hstrustedportid)
      continue;

    const listenAddress = (port.ip ? port.ip.includes('::') ? `[${port.ip}]:` : `${port.ip}:` : "") + port.port;
    const proxySettings = `proxy_pass http://hswebserver;
  proxy_http_version 1.1;
  proxy_set_header Upgrade $http_upgrade;
  proxy_set_header Connection $connection_upgrade;
  proxy_set_header Host $http_host;
  proxy_set_header X-Forwarded-For $remote_addr;
  proxy_set_header X-Forwarded-Proto $scheme;
  proxy_set_header X-WH-Proxy "source=nginx;proto=$scheme;for=$remote_addr;local=$server_addr${port.istrustedport ? "" : `;binding=${port.id}`}";`;
    const serverSection = `
listen ${listenAddress} ${port.privatekey ? "ssl" : ""};
server_name _; # listen to all hosts

# Load PEM certificate/chain and private key directly from RAM variables
ssl_certificate     data:$dynamic_cert_pem;
ssl_certificate_key data:$dynamic_key_pem;

# TODO what further ssl config is needed? eg:
# ssl_session_cache    shared:SSL:1m;
# ssl_session_timeout  5m;
# ssl_ciphers  HIGH:!aNULL:!MD5;
# ssl_prefer_server_ciphers  on;

# Set document root dynamically
root $dynamic_dataroot;
index index.shtml index.html;

location / {
  error_page 418 = @hswebserver;
  set $file_route $dynamic_file_route;
  if ($file_route = 418) {
    return 418;
  }
  if ($file_route = 403) {
    return 403;
  }
  if ($file_route = 303) {
    return 303 $file_redirect;
  }
  if ($file_route = 500) {
    return 500;
  }
  try_files $uri $uri/ @hswebserver;
}

location @hswebserver {
  error_page 419 = @hswebserver_websocket;
  if ($http_upgrade ~* ^websocket$) {
    return 419;
  }
  ${proxySettings}
}

location @hswebserver_websocket {
  # for compatibility with the current tollium sockets, they should be pinging less than every 5 minutes?
  proxy_read_timeout 5m;
  ${proxySettings}
}`; //end server block
    serverSections.push(`  server {\n${serverSection.split('\n').join('\n    ')}\n  }\n`);
  }

  return `# Generated by 'wh apply nginx' - ${new Date().toISOString()}

# Pass environment variable to NJS engine
env WEBHARE_DATAROOT;

load_module ${backendConfig.installationRoot}lib/ngx_http_js_module.so;

#user  nobody;
worker_processes  1; #FIXME should be configurable
daemon off;
pid        ${params.pidFile};

# TODO configure loglevel, eg notice or info. TODO can we make this json too? TODO log rotation, perhaps write through symlink?
error_log  ${backendConfig.dataRoot}log/nginx-error.log;

events {
 worker_connections  1024;
}

http {
  ${await generateMimeTypes(webserverConfig.types)}
  default_type  application/octet-stream;

  upstream hswebserver {
    server ${upstreamAddress};
  }

  map $http_upgrade $connection_upgrade {
    default upgrade;
    '' close;
  }

  # Select QuickJS, recommened for new code (https://github.com/nginx/njs/blob/master/README.md#javascript-engines)
  js_engine qjs;

  # Import the NJS module
  js_import router from "${params.routerFile}";

  # Define NJS variables
  js_set $dynamic_cert_pem router.getCertPem;
  js_set $dynamic_key_pem  router.getKeyPem;
  js_set $dynamic_dataroot router.getDataRootPath;
  js_set $dynamic_file_route router.getFileRoute nocache;
  js_var $file_redirect;
  js_set $log_timestamp router.getLogTimestamp;

  # Shared RAM dictionary (allocate 10-20MB for PEM strings)
  # FIXME what is a safe size?
  # FIXME how to ensure invalidation when a cert is renewed? and is invalidating this enough, apparently there's more SSL context caching in nginx itself?
  js_shared_dict_zone zone=cert_store:20m timeout=60m evict state=${params.configRoot}state/cert_store;

  log_format main escape=json '{"@timestamp":"$log_timestamp",'
                  '"timestampEpoch":$msec,"ip":"$remote_addr",'
                  '"method":"$request_method","url":"$scheme://$http_host$request_uri",'
                  '"statusCode":$status,"bodySent":$body_bytes_sent,'
                  '"userAgent":"$http_user_agent","mimeType":"$sent_http_content_type",'
                  '"totalTime":$request_time,"referer":"$http_referer",'
                  '"requestId":"$request_id","requestLength":$request_length,'
                  '"host":"$host","serverPort":$server_port,'
                  '"upstreamAddress":"$upstream_addr","upstreamStatus":"$upstream_status",'
                  '"upstreamConnectTime":"$upstream_connect_time",'
                  '"upstreamHeaderTime":"$upstream_header_time",'
                  '"responseTime":"$upstream_response_time",'
                  '"sslProtocol":"$ssl_protocol","sslCipher":"$ssl_cipher"}';

  access_log ${backendConfig.dataRoot}log/nginx-access.log main;

  sendfile        on;
  #tcp_nopush     on;

  #keepalive_timeout  0;
  keepalive_timeout  65;

  #gzip  on;

${serverSections.join("\n\n")}
}`;
}

export type NginxServerConfig = {
  /** Keyed by domain name (e.g., "app.example.com", "*.example.dev", "default") */
  domains: Record<string, {
    /** PEM encoded certificate */
    cert: string;
    /** PEM encoded private key */
    key: string;
    /** Root directory for the domain's data */
    dataRoot: string;
  }>;
};

async function generateServerConfig(webServerConfig: Configuration): Promise<NginxServerConfig> {
  const keypairs = await listStoredKeyPairsWithCertificates();
  const keystore = loadlib("mod::system/lib/keystore.whlib");
  const domains: NginxServerConfig["domains"] = {};
  for (const host of webServerConfig.hosts) {
    for (const listenhost of host.listenhosts) {
      if (listenhost === "_proxy" || listenhost.startsWith("*:"))
        continue;

      const domain = listenhost.replace(/:\d+$/, "").toLowerCase();
      const keypairId = await keystore.GetBestKeyPairForHostName(domain) as number;
      const keypair = keypairs.find(_ => _.id === keypairId);
      domains[domain] = {
        cert: keypair?.certificatechain ?? "",
        key: keypair?.privatekey ?? "",
        dataRoot: host.outputfolder
      };
    }
  }
  return { domains };
}

export async function reconfigureNginx() {
  const configRoot = backendConfig.dataRoot + "config/nginx/";
  //create configRoot and a state subfolder
  await mkdir(configRoot + "state", { recursive: true });

  const routerFile = configRoot + "nginx-router.js";
  //TODO in containers this should ship pregenerated unless code is changed
  //TODO consider using tsc instead and hand it nginx-router's tsconfig.json
  await ESBuild.build({
    entryPoints: [backendConfig.installationRoot + "nginx-router/nginx-router.ts"],
    bundle: true,
    external: ["fs"],
    platform: "neutral",
    format: "esm",
    outfile: routerFile
  });

  const webServerConfig = await loadlib("mod::system/lib/internal/webserver/config.whlib").DownloadWebserverConfig() as Configuration;
  const nginxServerConfig = await generateServerConfig(webServerConfig);
  await storeDiskFile(configRoot + "server-config.json", JSON.stringify(nginxServerConfig, null, 2), { overwrite: true });

  const pidFile = configRoot + "nginx.pid";
  const config = await generateBaseConfig(webServerConfig, { pidFile, routerFile, configRoot, });
  const configFile = configRoot + "nginx.conf";
  const configFileNew = configFile + ".new";
  await storeDiskFile(configFileNew, config, { overwrite: true });

  try {
    //TODO we could also consider -T (dumps config file) and save the full dump and input somewhere persistent for more debugging?
    await promisify(execFile)("nginx", ["-t", "-c", configFileNew]);
  } catch (e) {
    console.log(e);
    throw new Error("Nginx configuration test failed");
  }

  await rename(configFileNew, configFile);

  const pid = await attempt(async () => parseInt(await readFile(pidFile, "utf8"), 10));
  if (pid)
    await promisify(execFile)("nginx", ["-c", configFile, "-s", "reload"]);
}
